// @ts-check
// `node scripts/export-demo-spec.mjs` writes docs/demo-e2e-spec.md: the demo script's end-to-end spec (Gate C) as a document,
// built from the Playwright spec and its registry so it cannot be written by hand and drift. `scripts/lib.test.mjs` fails
// when the committed copy is out of date; run this to refresh it.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { ROOT } from './lib.mjs';

export const SPEC_FILE = 'apps/person/e2e/gate-c.spec.ts';
export const REGISTRY_FILE = 'apps/person/e2e/acceptance-c.json';
export const OUTPUT_FILE = 'docs/demo-e2e-spec.md';

/** The document text for the current spec and registry. */
export function renderDemoSpec() {
  const spec = readFileSync(resolve(ROOT, SPEC_FILE), 'utf8');
  /** @type {{ id: string, sentence: string }[]} */
  const registry = JSON.parse(readFileSync(resolve(ROOT, REGISTRY_FILE), 'utf8'));
  return [
    '# Demo end-to-end spec (Gate C)',
    '',
    'Generated by `node scripts/export-demo-spec.mjs` from `apps/person/e2e/gate-c.spec.ts` and `apps/person/e2e/acceptance-c.json`. Run it with `pnpm gate:c`.',
    '',
    'The demo script (steps 1 to 12) runs in Arabic and in English against the real API with `DEMO_MODE` on, the real person export and the real clinician and ops production builds. The browser fails on any console error and this gate excuses none, except the two 404s that the test of a phone opening its ticket after a real reset names. The demo clock is moved from the admin panel, not by a test hook, and the first step opens the mock TAMM page with the invite code the reset made.',
    '',
    '## Registered tests',
    '',
    ...registry.map((entry) => `- \`${entry.id}\`: ${entry.sentence}`),
    '',
    '## Source',
    '',
    '```ts',
    spec.trimEnd(),
    '```',
    '',
  ].join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) writeFileSync(resolve(ROOT, OUTPUT_FILE), renderDemoSpec());
