import { METRIC_DEFINITIONS, type MetricField } from '@mawsool/types';

type Messages = Record<string, unknown>;

/** A message by its dotted path; throws for one that is missing, so a definition without wording cannot be rendered. */
export function messageAt(messages: Messages, path: string): string {
  let node: unknown = messages;
  for (const part of path.split('.')) node = (node as Messages | undefined)?.[part];
  if (typeof node !== 'string' || node.trim() === '') throw new Error(`No message at "${path}"`);
  return node;
}

const fields = (list: readonly MetricField[]): string => (list.length === 0 ? 'none' : list.map((field) => `\`GET ${field.route}\` → \`${field.path}\``).join('; '));

/**
 * `docs/metric-definitions.md`, generated from the definitions list in `@mawsool/types` and the ops app's English and Arabic
 * wording. It is not edited by hand: `pnpm docs:metrics` rewrites it and a test fails when the file is out of date.
 */
export function renderMetricDefinitionsDoc(en: Messages, ar: Messages): string {
  const lines: string[] = [
    '# Metric definitions',
    '',
    'Generated by `pnpm docs:metrics` from `packages/types/src/metric-definitions.ts` and the ops app message files (`apps/ops/messages/en.json`, `ar.json`, under `defs`). Do not edit by hand: a test fails when this file is out of date.',
    '',
    'Each tile and section of the ops dashboard has an info panel with the text below, in both languages. "Computed from" names the fields of the metric routes the numerator and denominator are read from; a test checks every one against the route\'s response.',
    '',
  ];
  for (const definition of METRIC_DEFINITIONS) {
    const id = definition.id;
    lines.push(`## ${messageAt(en, definition.label)} (\`${id}\`)`, '', `- Surface: ${definition.surface}. Period kind: \`${definition.period}\`. Suppression kind: \`${definition.suppression}\`.`, `- Numerator computed from: ${fields(definition.numerator)}.`, `- Denominator computed from: ${fields(definition.denominator)}.`, '');
    for (const [name, messages] of [['English', en], ['Arabic', ar]] as const) {
      lines.push(
        `**${name}**`,
        '',
        `- Definition: ${messageAt(messages, `defs.${id}.definition`)}`,
        `- Numerator: ${messageAt(messages, `defs.${id}.numerator`)}`,
        `- Denominator: ${messageAt(messages, `defs.${id}.denominator`)}`,
        `- Period: ${messageAt(messages, `defs.period.${definition.period}`)}`,
        `- Suppression: ${messageAt(messages, `defs.suppression.${definition.suppression}`)}`,
        '',
      );
    }
  }
  return `${lines.join('\n').trimEnd()}\n`;
}
